#!/usr/bin/env python3
"""Generate gauge6_point_f32su.cpp: PT fused FD on a float shared tile.

Combines PT (one load + fused stencil, no Du/DDu passes) with F32C-style
centered float smem (~8.8KB → room for 2 blk/SM on GB200).
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

DD = {
    "gt0", "gt1", "gt2", "gt3", "gt4", "gt5", "chi",
    "alpha", "beta0", "beta1", "beta2",
}


def emit_derivs(var: str) -> str:
    lines = [
        f"device::__ld_blk_var1_f32_centered__<pw, nx>(su, {var}, blk);",
    ]
    if var in DD:
        lines += [
            f"DEVICE_REAL grad_0_{var}, grad2_0_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, grad2_1_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, grad2_2_2_{var}, kograd_2_{var};",
            f"device::__pt_fused_x3_f32su<nx>(su, i, j, k, inv_dx, "
            f"&grad_0_{var}, &grad2_0_0_{var}, &kograd_0_{var});",
            f"device::__pt_fused_y3_f32su<nx>(su, i, j, k, inv_dy, "
            f"&grad_1_{var}, &grad2_1_1_{var}, &kograd_1_{var});",
            f"device::__pt_fused_z3_f32su<nx>(su, i, j, k, inv_dz, "
            f"&grad_2_{var}, &grad2_2_2_{var}, &kograd_2_{var});",
            f"const DEVICE_REAL grad2_0_1_{var} = "
            f"device::__pt_dxy_f32su<nx>(su, i, j, k, inv_dx, inv_dy);",
            f"const DEVICE_REAL grad2_0_2_{var} = "
            f"device::__pt_dxz_f32su<nx>(su, i, j, k, inv_dx, inv_dz);",
            f"const DEVICE_REAL grad2_1_2_{var} = "
            f"device::__pt_dyz_f32su<nx>(su, i, j, k, inv_dy, inv_dz);",
            # Must finish all su reads before the next field's load overwrites su.
            "__syncthreads();",
        ]
    else:
        lines += [
            f"DEVICE_REAL grad_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, kograd_2_{var};",
            f"device::__pt_fused_x3_f32su<nx>(su, i, j, k, inv_dx, "
            f"&grad_0_{var}, nullptr, &kograd_0_{var});",
            f"device::__pt_fused_y3_f32su<nx>(su, i, j, k, inv_dy, "
            f"&grad_1_{var}, nullptr, &kograd_1_{var});",
            f"device::__pt_fused_z3_f32su<nx>(su, i, j, k, inv_dz, "
            f"&grad_2_{var}, nullptr, &kograd_2_{var});",
            "__syncthreads();",
        ]
    return "\n".join(lines) + "\n"


def strip_block_derivs(gauge6: str) -> str:
    ld_re = re.compile(
        r"device::__ld_blk_var1__<DEVICE_REAL,\s*pw,\s*nx>\(su,\s*(\w+),\s*blk\);"
    )
    parts = []
    pos = 0
    for m in ld_re.finditer(gauge6):
        parts.append(gauge6[pos:m.start()])
        var = m.group(1)
        rest = gauge6[m.end():]
        brace = re.search(r"\n(?=\s*\{)", rest)
        nxt_ld = re.search(r"\n(?=device::__ld_blk_var1__)", rest)
        candidates = [x.start() for x in (brace, nxt_ld) if x]
        if not candidates:
            raise RuntimeError(f"no end marker for {var}")
        end = min(candidates)
        parts.append(emit_derivs(var))
        pos = m.end() + end
    body = "".join(parts) + gauge6[pos:]
    # Keep the post-stencil syncs we emit; strip only leftover stock ones
    # that are not adjacent to our fused helpers (already replaced).
    return body


def main() -> None:
    src = (HERE / "bssneqs_eta_const_standard_gauge6.cpp").read_text()
    body = strip_block_derivs(src)
    out = (
        "// Auto-generated by gen_gauge6_point_f32su.py\n"
        "// PT fused FD on centered float shared tile (su only).\n"
        "const DEVICE_REAL inv_dx = 1.0 / blk->m_dx[0];\n"
        "const DEVICE_REAL inv_dy = 1.0 / blk->m_dx[1];\n"
        "const DEVICE_REAL inv_dz = 1.0 / blk->m_dx[2];\n"
        + body
    )
    dst = HERE / "gauge6_point_f32su.cpp"
    dst.write_text(out)
    print(f"wrote {dst} ({dst.stat().st_size} bytes)")
    print(f"ld_f32c: {out.count('__ld_blk_var1_f32_centered__')}")
    print(f"fused_f32su: {out.count('__pt_fused_x3_f32su')}")


if __name__ == "__main__":
    main()
