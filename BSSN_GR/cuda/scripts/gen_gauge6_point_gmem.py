#!/usr/bin/env python3
"""Generate gauge6_point_gmem.cpp: point-wise FD from global memory (no smem).

NCU on GB200: PT_ASYNC is limited to 1 block/SM by 17.6KB shared → 17%
occupancy. Direct global stencils drop smem to 0 so register limit (3 blk/SM)
can apply. Neighboring 7³ threads should still hit L1/L2 on the ±3 stencil.
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

DD = {
    "gt0", "gt1", "gt2", "gt3", "gt4", "gt5", "chi",
    "alpha", "beta0", "beta1", "beta2",
}


def emit_gmem_derivs(var: str) -> str:
    # Stencil helpers accept any DEVICE_REAL* — pass the unzipped field.
    if var in DD:
        lines = [
            f"DEVICE_REAL grad_0_{var}, grad2_0_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, grad2_1_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, grad2_2_2_{var}, kograd_2_{var};",
            f"PT_FUSED_X3<nx>({var}, i, j, k, inv_dx, &grad_0_{var}, "
            f"&grad2_0_0_{var}, &kograd_0_{var});",
            f"PT_FUSED_Y3<nx>({var}, i, j, k, inv_dy, &grad_1_{var}, "
            f"&grad2_1_1_{var}, &kograd_1_{var});",
            f"PT_FUSED_Z3<nx>({var}, i, j, k, inv_dz, &grad_2_{var}, "
            f"&grad2_2_2_{var}, &kograd_2_{var});",
            f"const DEVICE_REAL grad2_0_1_{var} = "
            f"device::__pt_dxy<nx>({var}, i, j, k, inv_dx, inv_dy);",
            f"const DEVICE_REAL grad2_0_2_{var} = "
            f"device::__pt_dxz<nx>({var}, i, j, k, inv_dx, inv_dz);",
            f"const DEVICE_REAL grad2_1_2_{var} = "
            f"device::__pt_dyz<nx>({var}, i, j, k, inv_dy, inv_dz);",
        ]
    else:
        lines = [
            f"DEVICE_REAL grad_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, kograd_2_{var};",
            f"PT_FUSED_X3<nx>({var}, i, j, k, inv_dx, &grad_0_{var}, "
            f"nullptr, &kograd_0_{var});",
            f"PT_FUSED_Y3<nx>({var}, i, j, k, inv_dy, &grad_1_{var}, "
            f"nullptr, &kograd_1_{var});",
            f"PT_FUSED_Z3<nx>({var}, i, j, k, inv_dz, &grad_2_{var}, "
            f"nullptr, &kograd_2_{var});",
        ]
    return "\n".join(lines) + "\n"


def strip_block_derivs(gauge6: str) -> str:
    ld_re = re.compile(
        r"device::__ld_blk_var1__<DEVICE_REAL,\s*pw,\s*nx>\(su,\s*(\w+),\s*blk\);"
    )
    parts = []
    pos = 0
    for m in ld_re.finditer(gauge6):
        parts.append(gauge6[pos:m.start()])
        var = m.group(1)
        rest = gauge6[m.end():]
        brace = re.search(r"\n(?=\s*\{)", rest)
        nxt_ld = re.search(r"\n(?=device::__ld_blk_var1__)", rest)
        candidates = [x.start() for x in (brace, nxt_ld) if x]
        if not candidates:
            raise RuntimeError(f"no end marker for {var}")
        end = min(candidates)
        parts.append(emit_gmem_derivs(var))
        pos = m.end() + end
    parts.append(gauge6[pos:])
    # Drop leftover __syncthreads that only guarded su reuse — none needed.
    body = "".join(parts)
    body = re.sub(r"\n\s*__syncthreads\(\);\s*\n", "\n", body)
    return body


def main() -> None:
    src = (HERE / "bssneqs_eta_const_standard_gauge6.cpp").read_text()
    body = strip_block_derivs(src)
    out = (
        "// Auto-generated by gen_gauge6_point_gmem.py — global-mem point FD.\n"
        "// No shared tile: raises GB200 occupancy vs PT_ASYNC (smem-bound).\n"
        "// Override PT_FUSED_{X,Y,Z}3 before include for KO-FP32 etc.\n"
        "#ifndef PT_FUSED_X3\n"
        "#define PT_FUSED_X3 device::__pt_fused_x3\n"
        "#define PT_FUSED_Y3 device::__pt_fused_y3\n"
        "#define PT_FUSED_Z3 device::__pt_fused_z3\n"
        "#endif\n"
        "const DEVICE_REAL inv_dx = 1.0 / blk->m_dx[0];\n"
        "const DEVICE_REAL inv_dy = 1.0 / blk->m_dx[1];\n"
        "const DEVICE_REAL inv_dz = 1.0 / blk->m_dx[2];\n"
        + body
    )
    dst = HERE / "gauge6_point_gmem.cpp"
    dst.write_text(out)
    print(f"wrote {dst} ({dst.stat().st_size} bytes)")
    print(f"syncthreads left: {out.count('__syncthreads')}")
    print(f"ld_blk left: {out.count('__ld_blk_var1')}")


if __name__ == "__main__":
    main()
