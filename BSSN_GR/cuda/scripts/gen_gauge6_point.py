#!/usr/bin/env python3
"""Generate gauge6_point.cpp: point-wise fused derivs + stock gauge6 algebra.

Items 1–2 from the smem-bound RHS plan: compute only the 7³ center, fuse
x/xx/ko (and y/z) into one su read, mixed seconds via register pencils.

Item 3 (algebra staging) was prototyped: deferring DD seconds until before K
is bit-identical but *slower* on A100 (0.157s vs 0.137s) — the 11-var reload
costs more than the live-range win. Keep unstaged as default.
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

DD = [
    "gt0", "gt1", "gt2", "gt3", "gt4", "gt5", "chi",
    "alpha", "beta0", "beta1", "beta2",
]


def emit_point_derivs(var: str) -> str:
    lines = [
        f"device::__ld_blk_var1__<DEVICE_REAL, pw, nx>(su, {var}, blk);",
    ]
    if var in DD:
        lines += [
            f"DEVICE_REAL grad_0_{var}, grad2_0_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, grad2_1_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, grad2_2_2_{var}, kograd_2_{var};",
            f"PT_FUSED_X3<nx>(su, i, j, k, inv_dx, &grad_0_{var}, "
            f"&grad2_0_0_{var}, &kograd_0_{var});",
            f"PT_FUSED_Y3<nx>(su, i, j, k, inv_dy, &grad_1_{var}, "
            f"&grad2_1_1_{var}, &kograd_1_{var});",
            f"PT_FUSED_Z3<nx>(su, i, j, k, inv_dz, &grad_2_{var}, "
            f"&grad2_2_2_{var}, &kograd_2_{var});",
            f"const DEVICE_REAL grad2_0_1_{var} = "
            f"device::__pt_dxy<nx>(su, i, j, k, inv_dx, inv_dy);",
            f"const DEVICE_REAL grad2_0_2_{var} = "
            f"device::__pt_dxz<nx>(su, i, j, k, inv_dx, inv_dz);",
            f"const DEVICE_REAL grad2_1_2_{var} = "
            f"device::__pt_dyz<nx>(su, i, j, k, inv_dy, inv_dz);",
            "__syncthreads();",
        ]
    else:
        lines += [
            f"DEVICE_REAL grad_0_{var}, kograd_0_{var};",
            f"DEVICE_REAL grad_1_{var}, kograd_1_{var};",
            f"DEVICE_REAL grad_2_{var}, kograd_2_{var};",
            f"PT_FUSED_X3<nx>(su, i, j, k, inv_dx, &grad_0_{var}, "
            f"nullptr, &kograd_0_{var});",
            f"PT_FUSED_Y3<nx>(su, i, j, k, inv_dy, &grad_1_{var}, "
            f"nullptr, &kograd_1_{var});",
            f"PT_FUSED_Z3<nx>(su, i, j, k, inv_dz, &grad_2_{var}, "
            f"nullptr, &kograd_2_{var});",
            "__syncthreads();",
        ]
    return "\n".join(lines) + "\n"


def strip_block_derivs(gauge6: str) -> str:
    ld_re = re.compile(
        r"device::__ld_blk_var1__<DEVICE_REAL,\s*pw,\s*nx>\(su,\s*(\w+),\s*blk\);"
    )
    parts = []
    pos = 0
    for m in ld_re.finditer(gauge6):
        parts.append(gauge6[pos:m.start()])
        var = m.group(1)
        rest = gauge6[m.end():]
        brace = re.search(r"\n(?=\s*\{)", rest)
        nxt_ld = re.search(r"\n(?=device::__ld_blk_var1__)", rest)
        candidates = [x.start() for x in (brace, nxt_ld) if x]
        if not candidates:
            raise RuntimeError(f"no end marker for {var}")
        end = min(candidates)
        parts.append(emit_point_derivs(var))
        pos = m.end() + end
    parts.append(gauge6[pos:])
    return "".join(parts)


def main() -> None:
    src = (HERE / "bssneqs_eta_const_standard_gauge6.cpp").read_text()
    body = strip_block_derivs(src)
    out = (
        "// Auto-generated by gen_gauge6_point.py — point-wise fused derivs.\n"
        "// Interior stencils only (matches rhsgpu_test bflag=0).\n"
        "// Override PT_FUSED_{X,Y,Z}3 before include for KO-FP32 etc.\n"
        "#ifndef PT_FUSED_X3\n"
        "#define PT_FUSED_X3 device::__pt_fused_x3\n"
        "#define PT_FUSED_Y3 device::__pt_fused_y3\n"
        "#define PT_FUSED_Z3 device::__pt_fused_z3\n"
        "#endif\n"
        "const DEVICE_REAL inv_dx = 1.0 / blk->m_dx[0];\n"
        "const DEVICE_REAL inv_dy = 1.0 / blk->m_dx[1];\n"
        "const DEVICE_REAL inv_dz = 1.0 / blk->m_dx[2];\n"
        + body
    )
    dst = HERE / "gauge6_point.cpp"
    dst.write_text(out)
    print(f"wrote {dst} ({dst.stat().st_size} bytes)")
    assert "a_rhs[pp]" in out
    n_blk = out.count("__blk1_deriv")
    print(f"remaining __blk1_deriv: {n_blk}")
    if n_blk:
        print("WARNING: block-pass derivs remain")


if __name__ == "__main__":
    main()
