#!/usr/bin/env python3
"""Emit gauge6_point_async_defer.cpp — defer DD second derivs until late use.

First pass for DD vars: first+KO only (nullptr seconds, no mixed).
Before K_rhs / Gt / At Ricci: reload each DD var and fill seconds.

Bit-identical to unstaged if stencils match; GB200 A/B vs PT_ASYNC.
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Vars whose seconds are expensive and only needed late.
DD = [
    "alpha", "beta0", "beta1", "beta2", "chi",
    "gt0", "gt1", "gt2", "gt3", "gt4", "gt5",
]

# Insert seconds-fill just before these markers (first occurrence).
INSERT_BEFORE = {
    # K_rhs uses grad2_*_alpha
    "alpha": "    K_rhs[pp] =",
    # Gt algebra uses grad2_*_beta*
    "beta0": "    const double DENDRO_50 = beta0[pp] * grad_0_Gt0",
    # fallback if DENDRO_50 form differs — Gt_rhs0 assignment
}


def first_only_block(var: str) -> str:
    return f"""device::__ld_blk_var1_async_issue__<nx>(su, {var});
device::__ld_blk_var1_async_wait__();
DEVICE_REAL grad_0_{var}, kograd_0_{var};
DEVICE_REAL grad_1_{var}, kograd_1_{var};
DEVICE_REAL grad_2_{var}, kograd_2_{var};
// DEFER_DD: seconds filled later
DEVICE_REAL grad2_0_0_{var}=0, grad2_1_1_{var}=0, grad2_2_2_{var}=0;
DEVICE_REAL grad2_0_1_{var}=0, grad2_0_2_{var}=0, grad2_1_2_{var}=0;
PT_FUSED_X3<nx>(su, i, j, k, inv_dx, &grad_0_{var}, nullptr, &kograd_0_{var});
PT_FUSED_Y3<nx>(su, i, j, k, inv_dy, &grad_1_{var}, nullptr, &kograd_1_{var});
PT_FUSED_Z3<nx>(su, i, j, k, inv_dz, &grad_2_{var}, nullptr, &kograd_2_{var});
__syncthreads();
"""


def seconds_fill_block(var: str) -> str:
    return f"""// DEFER_DD fill seconds: {var}
device::__ld_blk_var1_async_issue__<nx>(su, {var});
device::__ld_blk_var1_async_wait__();
{{
  DEVICE_REAL _dxx, _dyy, _dzz, _kx, _ky, _kz, _g0, _g1, _g2;
  PT_FUSED_X3<nx>(su, i, j, k, inv_dx, &_g0, &grad2_0_0_{var}, &_kx);
  PT_FUSED_Y3<nx>(su, i, j, k, inv_dy, &_g1, &grad2_1_1_{var}, &_ky);
  PT_FUSED_Z3<nx>(su, i, j, k, inv_dz, &_g2, &grad2_2_2_{var}, &_kz);
  grad2_0_1_{var} = device::__pt_dxy<nx>(su, i, j, k, inv_dx, inv_dy);
  grad2_0_2_{var} = device::__pt_dxz<nx>(su, i, j, k, inv_dx, inv_dz);
  grad2_1_2_{var} = device::__pt_dyz<nx>(su, i, j, k, inv_dy, inv_dz);
  (void)_dxx; (void)_dyy; (void)_dzz; (void)_g0; (void)_g1; (void)_g2;
  (void)_kx; (void)_ky; (void)_kz;
}}
__syncthreads();
"""


def replace_first_deriv_block(text: str, var: str) -> str:
    """Replace the full first-load+all-derivs block for var with first-only."""
    # Match from async_issue of var through its syncthreads after mixed seconds.
    pat = re.compile(
        rf"device::__ld_blk_var1_async_issue__<nx>\(su, {var}\);\n"
        rf"device::__ld_blk_var1_async_wait__\(\);\n"
        rf"DEVICE_REAL grad_0_{var}, grad2_0_0_{var}, kograd_0_{var};\n"
        rf"DEVICE_REAL grad_1_{var}, grad2_1_1_{var}, kograd_1_{var};\n"
        rf"DEVICE_REAL grad_2_{var}, grad2_2_2_{var}, kograd_2_{var};\n"
        rf"PT_FUSED_X3<nx>\(su, i, j, k, inv_dx, &grad_0_{var}, &grad2_0_0_{var}, &kograd_0_{var}\);\n"
        rf"PT_FUSED_Y3<nx>\(su, i, j, k, inv_dy, &grad_1_{var}, &grad2_1_1_{var}, &kograd_1_{var}\);\n"
        rf"PT_FUSED_Z3<nx>\(su, i, j, k, inv_dz, &grad_2_{var}, &grad2_2_2_{var}, &kograd_2_{var}\);\n"
        rf"const DEVICE_REAL grad2_0_1_{var} = device::__pt_dxy<nx>\(su, i, j, k, inv_dx, inv_dy\);\n"
        rf"const DEVICE_REAL grad2_0_2_{var} = device::__pt_dxz<nx>\(su, i, j, k, inv_dx, inv_dz\);\n"
        rf"const DEVICE_REAL grad2_1_2_{var} = device::__pt_dyz<nx>\(su, i, j, k, inv_dy, inv_dz\);\n"
        rf"__syncthreads\(\);\n",
        re.MULTILINE,
    )
    new, n = pat.subn(first_only_block(var), text, count=1)
    if n != 1:
        raise RuntimeError(f"failed to rewrite first block for {var} (n={n})")
    return new


def main() -> None:
    src = (HERE / "gauge6_point_async.cpp").read_text()
    # Drop the "Auto-generated by gen_gauge6_point" banner note
    out = src
    for var in DD:
        out = replace_first_deriv_block(out, var)

    # Insert seconds fills: alpha before K_rhs; betas before Gt temps;
    # chi+gt before At Ricci (DENDRO_RIJ / first big At block).
    def insert_before(text: str, marker: str, block: str) -> str:
        i = text.find(marker)
        if i < 0:
            raise RuntimeError(f"marker not found: {marker[:60]}")
        return text[:i] + block + text[i:]

    # Statement-boundary inserts only (never mid-expression).
    out = insert_before(out, "    K_rhs[pp] =", seconds_fill_block("alpha"))

    # Gt: DENDRO_51 is the first temp that consumes beta seconds.
    beta_fills = "".join(seconds_fill_block(v) for v in ("beta0", "beta1", "beta2"))
    out = insert_before(out, "    const double DENDRO_51 =", beta_fills)

    # Ricci: DENDRO_RIJ0 is the first assignment that consumes gt/chi seconds.
    gt_fills = "".join(
        seconds_fill_block(v)
        for v in ("chi", "gt0", "gt1", "gt2", "gt3", "gt4", "gt5")
    )
    out = insert_before(out, "        DENDRO_RIJ0 =", gt_fills)

    header = (
        "// Auto-generated by gen_gauge6_defer_dd.py — DEFER second derivs.\n"
        "// First+KO early; reload+seconds before K / Gt / At Ricci.\n"
    )
    # Replace original banner
    out = re.sub(
        r"^// Auto-generated by gen_gauge6_point\.py.*\n(//.*\n)*",
        header,
        out,
        count=1,
    )

    dst = HERE / "gauge6_point_async_defer.cpp"
    dst.write_text(out)
    print(f"wrote {dst} ({dst.stat().st_size} bytes)")
    print(f"DEFER_DD markers: {out.count('DEFER_DD')}")


if __name__ == "__main__":
    main()
