#!/usr/bin/env python3
"""Generate the CAHD (constraint-adjusted Hamiltonian damping) device code from the CPU equations
(BSSN_GR/src/bssneqs_SSL_HD_dxsq.cpp) so the GPU term is identical by construction.

CPU:  chi_rhs = -C*DENDRO_18*DENDRO_640*(BRACKET)/(dt*(10*DENDRO_18+1)) + <rest of chi RHS>
with DENDRO_18 = dx_i^2, DENDRO_640 = chi/12.
Outputs cahd_gen.inc.cuh with:
  CAHD_DERIV_LIST(X)        X(name) for every derivative array the bracket needs
  CAHD_FIELD_LIST(X)        X(name, VAR_ID) for every field array used
  CAHD_BRACKET_BODY         statements computing `const double cahd_bracket` at point pp
"""
import re,sys,os
src=os.path.join(os.path.dirname(__file__),"../../src/bssneqs_SSL_HD_dxsq.cpp")
t=open(src).read()
defs={}   # name -> expr, in order
order=[]
for m in re.finditer(r"const double (DENDRO_\d+)\s*=\s*([^;]*);",t):
    defs[m.group(1)]=m.group(2); order.append(m.group(1))
m=re.search(r"chi_rhs\[pp\]\s*=\s*(.*?);\s*\n",t,flags=re.S)
stmt=m.group(1)
pre="-BSSN_CAHD_C*DENDRO_18*DENDRO_640*("
i=stmt.index(pre)+len(pre)
depth=1;j=i
while depth:
    c=stmt[j]; depth+= (c=='(') - (c==')'); j+=1
bracket=stmt[i:j-1]
tail=stmt[j:j+30]
assert tail.startswith("/(dt*(10*DENDRO_18 + 1))"),tail
# transitive temps
need=set(re.findall(r"DENDRO_\d+",bracket)); seen=set(); st=list(need)
while st:
    x=st.pop()
    if x in seen: continue
    seen.add(x)
    st+=re.findall(r"DENDRO_\d+",defs[x])
body=[f"const double {x} = {defs[x]};" for x in order if x in seen and x not in ("DENDRO_18",)]
alltxt=bracket+" ".join(defs[x] for x in seen)
derivs=sorted(set(re.findall(r"(grad2?_\d(?:_\d)?_[A-Za-z0-9]+)\[pp\]",alltxt)))
fields=sorted(set(re.findall(r"\b(alpha|chi|K|gt\d|At\d|Gt\d|beta\d|B\d)\[pp\]",alltxt)))
vid={"alpha":"U_ALPHA","chi":"U_CHI","K":"U_K","beta0":"U_BETA0","beta1":"U_BETA1","beta2":"U_BETA2",
     "B0":"U_B0","B1":"U_B1","B2":"U_B2","Gt0":"U_GT0","Gt1":"U_GT1","Gt2":"U_GT2"}
for k in range(6): vid[f"gt{k}"]=f"U_SYMGT{k}"; vid[f"At{k}"]=f"U_SYMAT{k}"
# which variables' derivative CTAs are needed
dvars=sorted(set(re.sub(r"^grad2?_\d(?:_\d)?_","",d) for d in derivs))
out=["// GENERATED by gen_cahd.py from src/bssneqs_SSL_HD_dxsq.cpp -- do not edit",
     "#pragma once",
     "#define CAHD_DERIV_LIST(X) \\"]+[f"  X({d}) \\" for d in derivs]+[""]
out+=["#define CAHD_FIELD_LIST(X) \\"]+[f"  X({f}, {vid[f]}) \\" for f in fields]+[""]
out+=["// variables (by name) whose derivative CTAs are required: "+" ".join(dvars)]
out+=["#define CAHD_BRACKET_BODY \\"]+[ "  "+l+" \\" for l in body]+[f"  const double cahd_bracket = {bracket};",""]
open(os.path.join(os.path.dirname(__file__),"../include/cahd_gen.inc.cuh"),"w").write("\n".join(out))
print("derivs",len(derivs),"fields",fields,"dvars",dvars,"temps",len(body),"bracket chars",len(bracket))
