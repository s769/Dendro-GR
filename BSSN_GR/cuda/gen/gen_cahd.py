#!/usr/bin/env python3
"""Generate the CAHD (constraint-adjusted Hamiltonian damping) device code from the CPU equations
(BSSN_GR/src/bssneqs_SSL_HD_dxsq.cpp) so the GPU term is identical by construction.

CPU:  chi_rhs = -C*DENDRO_18*DENDRO_640*(BRACKET)/(dt*(10*DENDRO_18+1)) + <rest of chi RHS>
with DENDRO_18 = dx_i^2, DENDRO_640 = chi/12.
Outputs cahd_gen.inc.cuh with:
  CAHD_DERIV_LIST(X)        X(name) for every derivative array the bracket needs
  CAHD_FIELD_LIST(X)        X(name, VAR_ID) for every field array used
  CAHD_BRACKET_BODY         statements computing `const double cahd_bracket` at point pp
"""
import re,sys,os
src=os.path.join(os.path.dirname(__file__),"../../src/bssneqs_SSL_HD_dxsq.cpp")
t=open(src).read()
defs={}   # name -> expr, in order
order=[]
for m in re.finditer(r"const double (DENDRO_\d+)\s*=\s*([^;]*);",t):
    defs[m.group(1)]=m.group(2); order.append(m.group(1))
m=re.search(r"chi_rhs\[pp\]\s*=\s*(.*?);\s*\n",t,flags=re.S)
stmt=m.group(1)
pre="-BSSN_CAHD_C*DENDRO_18*DENDRO_640*("
i=stmt.index(pre)+len(pre)
depth=1;j=i
while depth:
    c=stmt[j]; depth+= (c=='(') - (c==')'); j+=1
bracket=stmt[i:j-1]
tail=stmt[j:j+30]
assert tail.startswith("/(dt*(10*DENDRO_18 + 1))"),tail
# transitive temps
need=set(re.findall(r"DENDRO_\d+",bracket)); seen=set(); st=list(need)
while st:
    x=st.pop()
    if x in seen: continue
    seen.add(x)
    st+=re.findall(r"DENDRO_\d+",defs[x])
body=[f"const double {x} = {defs[x]};" for x in order if x in seen and x not in ("DENDRO_18",)]
alltxt=bracket+" ".join(defs[x] for x in seen)
derivs=sorted(set(re.findall(r"(grad2?_\d(?:_\d)?_[A-Za-z0-9]+)\[pp\]",alltxt)))
fields=sorted(set(re.findall(r"\b(alpha|chi|K|gt\d|At\d|Gt\d|beta\d|B\d)\[pp\]",alltxt)))
vid={"alpha":"U_ALPHA","chi":"U_CHI","K":"U_K","beta0":"U_BETA0","beta1":"U_BETA1","beta2":"U_BETA2",
     "B0":"U_B0","B1":"U_B1","B2":"U_B2","Gt0":"U_GT0","Gt1":"U_GT1","Gt2":"U_GT2"}
for k in range(6): vid[f"gt{k}"]=f"U_SYMGT{k}"; vid[f"At{k}"]=f"U_SYMAT{k}"
# which variables' derivative CTAs are needed
dvars=sorted(set(re.sub(r"^grad2?_\d(?:_\d)?_","",d) for d in derivs))
out=["// GENERATED by gen_cahd.py from src/bssneqs_SSL_HD_dxsq.cpp -- do not edit",
     "#pragma once",
     "#define CAHD_DERIV_LIST(X) \\"]+[f"  X({d}) \\" for d in derivs]+[""]
out+=["#define CAHD_FIELD_LIST(X) \\"]+[f"  X({f}, {vid[f]}) \\" for f in fields]+[""]
out+=["// variables (by name) whose derivative CTAs are required: "+" ".join(dvars)]
out+=["#define CAHD_BRACKET_BODY \\"]+[ "  "+l+" \\" for l in body]+[f"  const double cahd_bracket = {bracket};",""]
open(os.path.join(os.path.dirname(__file__),"../include/cahd_gen.inc.cuh"),"w").write("\n".join(out))
print("derivs",len(derivs),"fields",fields,"dvars",dvars,"temps",len(body),"bracket chars",len(bracket))

# ---- trimmed derivative script: only the sections for variables the bracket needs, no KO derivatives ----
scr=open(os.path.join(os.path.dirname(__file__),"../scripts/compute_bssnrhs_evar_derivs2.cuh")).read()
need_ids={1,3,4,5,12,13,14,15,16,17}   # chi, Gt0..2, SYMGT0..5 (grDef.h layout)
secs=re.findall(r"(if\(V_ID == (\d+)\) \{.*?\} // end of var [^\n]*\n)",scr,flags=re.S)
keep=[]
for secbody,vid_ in secs:
    if int(vid_) in need_ids:
        lines=[l for l in secbody.split("\n") if "ko_deriv" not in l]
        keep.append("\n".join(lines))
open(os.path.join(os.path.dirname(__file__),"../include/cahd_derivs_body.inc.cuh"),"w").write("// GENERATED by gen_cahd.py: derivative sections for chi/Gt/gt only, no KO\n"+"\n".join(keep)+"\n")
print("derivative sections kept:",len(keep))

# ---- fused kernel pieces: per-variable derivative statements (registers) + scalar bracket body ----
# (variable ids by NAME so the VAR layout cannot be gotten wrong again)
vname={"chi":"U_CHI","Gt0":"U_GT0","Gt1":"U_GT1","Gt2":"U_GT2"}
for k in range(6): vname[f"gt{k}"]=f"U_SYMGT{k}"
second=["chi"]+[f"gt{k}" for k in range(6)]          # variables with second-derivative arrays in the bracket
decl=sorted(derivs)
code=[]
code.append("// GENERATED by gen_cahd.py: fused derivative statements. Requires in scope: s (smem 13^3), i,j,k, tid,\n"
            "// ix60,iy60,iz60, ixx180,iyy180,izz180, dptr_u, sz_per_dof, offset, and the lambdas below.")
code.append("auto Sx = [&](int di,int dj,int dk){ return s[(i+di)+nx*((j+dj)+nx*(k+dk))]; };")
code.append("auto d1x = [&](int dj,int dk){ return (-Sx(-3,dj,dk)+9.0*Sx(-2,dj,dk)-45.0*Sx(-1,dj,dk)+45.0*Sx(1,dj,dk)-9.0*Sx(2,dj,dk)+Sx(3,dj,dk))*ix60; };")
code.append("auto d1y = [&](int di,int dk){ return (-Sx(di,-3,dk)+9.0*Sx(di,-2,dk)-45.0*Sx(di,-1,dk)+45.0*Sx(di,1,dk)-9.0*Sx(di,2,dk)+Sx(di,3,dk))*iy60; };")
code.append("auto d1z = [&](int di,int dj){ return (-Sx(di,dj,-3)+9.0*Sx(di,dj,-2)-45.0*Sx(di,dj,-1)+45.0*Sx(di,dj,1)-9.0*Sx(di,dj,2)+Sx(di,dj,3))*iz60; };")
code.append("auto st = [&](const double* a, double c){ return (-a[0]+9.0*a[1]-45.0*a[2]+45.0*a[4]-9.0*a[5]+a[6])*c; };")
for d in decl: code.append(f"double {d};")
for v in ["chi","Gt0","Gt1","Gt2"]+[f"gt{k}" for k in range(6)]:
    code.append(f"{{ // variable {v}")
    code.append(f"  for (unsigned q = tid; q < nx*nx*nx; q += blockDim.x) s[q] = dptr_u[(size_t)bssn::VAR::{vname[v]} * sz_per_dof + offset + q];")
    code.append("  __syncthreads();")
    code.append(f"  grad_0_{v} = d1x(0,0); grad_1_{v} = d1y(0,0); grad_2_{v} = d1z(0,0);")
    if v in second:
        code.append(f"  grad2_0_0_{v} = (2.0*Sx(-3,0,0)-27.0*Sx(-2,0,0)+270.0*Sx(-1,0,0)-490.0*Sx(0,0,0)+270.0*Sx(1,0,0)-27.0*Sx(2,0,0)+2.0*Sx(3,0,0))*ixx180;")
        code.append(f"  grad2_1_1_{v} = (2.0*Sx(0,-3,0)-27.0*Sx(0,-2,0)+270.0*Sx(0,-1,0)-490.0*Sx(0,0,0)+270.0*Sx(0,1,0)-27.0*Sx(0,2,0)+2.0*Sx(0,3,0))*iyy180;")
        code.append(f"  grad2_2_2_{v} = (2.0*Sx(0,0,-3)-27.0*Sx(0,0,-2)+270.0*Sx(0,0,-1)-490.0*Sx(0,0,0)+270.0*Sx(0,0,1)-27.0*Sx(0,0,2)+2.0*Sx(0,0,3))*izz180;")
        code.append("  { double a[7];")
        code.append("    #pragma unroll\n    for (int q=-3;q<=3;q++) a[q+3]=d1x(q,0);")
        code.append(f"    grad2_0_1_{v} = st(a, iy60);")
        code.append("    #pragma unroll\n    for (int q=-3;q<=3;q++) a[q+3]=d1x(0,q);")
        code.append(f"    grad2_0_2_{v} = st(a, iz60);")
        code.append("    #pragma unroll\n    for (int q=-3;q<=3;q++) a[q+3]=d1y(0,q);")
        code.append(f"    grad2_1_2_{v} = st(a, iz60); }}")
    code.append("  __syncthreads();")
    code.append("}")
open(os.path.join(os.path.dirname(__file__),"../include/cahd_fused_derivs.inc.cuh"),"w").write("\n".join(code)+"\n")
# scalar version of the bracket body: NAME[pp] -> NAME
sc_body=[re.sub(r"\[pp\]","",l) for l in body]
sc_br=re.sub(r"\[pp\]","",bracket)
open(os.path.join(os.path.dirname(__file__),"../include/cahd_bracket_scalar.inc.cuh"),"w").write(
  "\n".join(sc_body)+f"\nconst double cahd_bracket = {sc_br};\n")
print("fused: derivative statements for",len(decl),"values; scalar bracket temps",len(sc_body))
