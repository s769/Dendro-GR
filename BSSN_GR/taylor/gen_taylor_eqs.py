#!/usr/bin/env python3
"""Generate the Taylor-typed pointwise BSSN algebra from the production generated equation file.

usage: gen_taylor_eqs.py <path to src/bssneqs_SSL_HD_dxsq.cpp> <path to scripts/bssnrhs_ko_derivs.h> <outdir>
writes  taylor_names.inc   (X-macro name lists: fields, derivative arrays, outputs, KO arrays)
        taylor_point.inc   (the equation body with `double` temporaries -> `T`, NAME[pp] -> NAME_T, NAME_rhs[pp]= -> OUT_NAME=)
"""
import re, sys

eq_path, ko_path, outdir = sys.argv[1:4]
FIELDS = {  # production name -> VAR enum suffix
    'alpha': 'U_ALPHA', 'chi': 'U_CHI', 'K': 'U_K',
    **{f'gt{i}': f'U_SYMGT{i}' for i in range(6)},
    **{f'beta{i}': f'U_BETA{i}' for i in range(3)},
    **{f'At{i}': f'U_SYMAT{i}' for i in range(6)},
    **{f'Gt{i}': f'U_GT{i}' for i in range(3)},
    **{f'B{i}': f'U_B{i}' for i in range(3)},
}
OUTS = {  # rhs name -> (VAR suffix, field name)
    'a_rhs': ('U_ALPHA', 'alpha'), 'chi_rhs': ('U_CHI', 'chi'), 'K_rhs': ('U_K', 'K'),
    **{f'b_rhs{i}': (f'U_BETA{i}', f'beta{i}') for i in range(3)},
    **{f'B_rhs{i}': (f'U_B{i}', f'B{i}') for i in range(3)},
    **{f'Gt_rhs{i}': (f'U_GT{i}', f'Gt{i}') for i in range(3)},
    'gt_rhs00': ('U_SYMGT0', 'gt0'), 'gt_rhs01': ('U_SYMGT1', 'gt1'), 'gt_rhs02': ('U_SYMGT2', 'gt2'),
    'gt_rhs11': ('U_SYMGT3', 'gt3'), 'gt_rhs12': ('U_SYMGT4', 'gt4'), 'gt_rhs22': ('U_SYMGT5', 'gt5'),
    'At_rhs00': ('U_SYMAT0', 'At0'), 'At_rhs01': ('U_SYMAT1', 'At1'), 'At_rhs02': ('U_SYMAT2', 'At2'),
    'At_rhs11': ('U_SYMAT3', 'At3'), 'At_rhs12': ('U_SYMAT4', 'At4'), 'At_rhs22': ('U_SYMAT5', 'At5'),
}
txt = open(eq_path).read()
body = []
inputs = set()
for line in txt.splitlines():
    s = line.strip()
    if not s or s.startswith('//'):
        continue
    m = re.match(r'^(\w+)\[pp\]\s*=\s*(.*);$', s)
    if m and m.group(1) in OUTS:
        name, expr = m.group(1), m.group(2)
        for n in re.findall(r'\b(\w+)\[pp\]', expr):
            inputs.add(n)
        expr = re.sub(r'\b(\w+)\[pp\]', r'\1_T', expr)
        body.append(f'OUT_{name} = {expr};')
        continue
    s2 = re.sub(r'^const double (DENDRO_\w+)\s*=', r'const T \1 =', s)
    for n in re.findall(r'\b(\w+)\[pp\]', s2):
        inputs.add(n)
    s2 = re.sub(r'\b(\w+)\[pp\]', r'\1_T', s2)
    body.append(s2)
fields_used = sorted(n for n in inputs if n in FIELDS)
deriv_used = sorted(n for n in inputs if n not in FIELDS)
assert all(n.startswith('grad') for n in deriv_used), deriv_used
with open(f'{outdir}/taylor_point.inc', 'w') as f:
    f.write('// GENERATED by gen_taylor_eqs.py from the production equation file: do not edit\n')
    f.write('\n'.join(body) + '\n')

# KO derivative arrays: the production fragment writes ko_deriv_{x,y,z}(grad_i_<var>, <var>, ...): collect (axis, var)
ko = open(ko_path).read()
ko_arrays = re.findall(r'ko_deriv_([xyz])\((grad_[012]_\w+),\s*(\w+),', ko)
with open(f'{outdir}/taylor_names.inc', 'w') as f:
    f.write('// GENERATED by gen_taylor_eqs.py: X-macro name lists\n')
    f.write('#define TAYLOR_FIELD_NAMES(X) \\\n' + ' \\\n'.join(f'  X({n}, {FIELDS[n]})' for n in sorted(FIELDS)) + '\n')
    f.write('#define TAYLOR_FIELD_USED(X) \\\n' + ' \\\n'.join(f'  X({n})' for n in fields_used) + '\n')
    f.write('#define TAYLOR_DERIV_NAMES(X) \\\n' + ' \\\n'.join(f'  X({n})' for n in deriv_used) + '\n')
    f.write('#define TAYLOR_OUT_NAMES(X) \\\n' + ' \\\n'.join(f'  X({n}, {OUTS[n][0]}, {OUTS[n][1]})' for n in sorted(OUTS)) + '\n')
    f.write('#define TAYLOR_KO_NAMES(X) \\\n' + ' \\\n'.join(f'  X({a}, {v})' for (_, a, v) in ko_arrays) + '\n')
print(f'{len(body)} statements, {len(fields_used)} field inputs, {len(deriv_used)} derivative inputs, {len(ko_arrays)} KO arrays')
